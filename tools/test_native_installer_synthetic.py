#!/usr/bin/env python3
"""Exercise the template's safety functions using only newly authored fixtures.

Never start a browser, the production-shaped syntax setup, or a real installer.
Execution is limited to the explicitly compiled synthetic entry points on the
ephemeral hosted Windows runner, with every test path below a fixed fresh root.
"""
from __future__ import annotations

from contextlib import contextmanager
import ctypes
from ctypes import wintypes
import json
import os
import ntpath
from pathlib import Path
import subprocess

import verify_windows_native as native
from windows_native_evidence import write_json

EXECUTION_RELATIVE = "installer-syntax/execution"
EXECUTION_WINDOWS = r"D:\pb\installer-syntax\execution"
FIXTURE_EXE = "NONPRODUCTION-synthetic-safety.exe"
MARKER = "PrivacyBrowser.userdata-owner"
SHORTCUT_OUTPUT = "installer-synthetic-shortcuts.json"
SHORTCUT_MAX_BYTES = 1024 * 1024
SHORTCUT_ROOT = EXECUTION_WINDOWS + r"\app\shortcut-probe"
SHORTCUT_CASES = (("ascii", "PrivacyBrowser-ASCII", "ascii profile"),
                  ("unicode", "PrivacyBrowser-日本語", "日本語 profile"),
                  ("unicode-space", "PrivacyBrowser 日本語 Space", "日本語 space profile"))
SHORTCUT_LINKS = (("direct", "direct.lnk", True),
                  ("desktop-snapshot", "PrivacyBrowser.desktop-link", False),
                  ("program-snapshot", "PrivacyBrowser.program-link", False),
                  ("desktop-copy", r"relocated\desktop.lnk", True),
                  ("program-copy", r"relocated\program.lnk", True))
SHORTCUT_ASCII_LINKS = (("desktop-ascii-copy", "desktop.lnk", True),
                        ("program-ascii-copy", "program.lnk", True))
FILE_COUNT = 1500  # More than one 64-KiB FILE_FULL_DIR_INFO enumeration buffer.


def require_host(work: Path) -> None:
    native.require(os.name == "nt" and os.environ.get("GITHUB_ACTIONS") == "true"
                   and os.environ.get("RUNNER_ENVIRONMENT") == "github-hosted",
                   "Synthetic execution requires the ephemeral GitHub-hosted Windows runner")
    native.require(str(work.resolve()).lower() == r"d:\pb", "Expected fixed synthetic workspace D:\\pb")
    for path in (work, work / "installer-syntax", work / EXECUTION_RELATIVE):
        native.require(path.is_dir() and not native.is_link_or_reparse(path), "Unsafe synthetic fixture parent")


def fixture_environment(root: Path) -> dict[str, str]:
    environment = os.environ.copy()
    # The template hardcodes its own roots too; environment variables alone do
    # not redirect Windows shell constants. This also confines NSIS plug-in temp.
    environment.update(TEMP=str(root / "tmp"), TMP=str(root / "tmp"),
                       APPDATA=str(root / "roaming"), LOCALAPPDATA=str(root / "local"))
    return environment


def snapshot(roots: list[Path]) -> dict[str, str]:
    """Hash only regular synthetic entries; never traverse any reparse point."""
    result = {}
    for index, root in enumerate(roots):
        native.require(root.is_dir() and not native.is_link_or_reparse(root), "Missing owned synthetic root")
        for directory, folders, files in os.walk(root, followlinks=False):
            for name in folders + files:
                path = Path(directory) / name
                native.require(not native.is_link_or_reparse(path), "Unexpected fixture reparse point")
                key = str(index) + "/" + path.relative_to(root).as_posix()
                result[key] = "directory" if path.is_dir() else native.digest(path)
    return result


@contextmanager
def locked_file(path: Path):
    """Hold one synthetic file with share mode zero; never lock outside root."""
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel.CreateFileW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                                  wintypes.LPVOID, wintypes.DWORD, wintypes.DWORD, wintypes.HANDLE]
    kernel.CreateFileW.restype = wintypes.HANDLE
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    kernel.CloseHandle.restype = wintypes.BOOL
    handle = kernel.CreateFileW(str(path), 0x80000000, 0, None, 3, 0x80, None)
    native.require(handle not in (None, ctypes.c_void_p(-1).value), "Cannot lock synthetic fixture file")
    try:
        yield
    finally:
        native.require(bool(kernel.CloseHandle(handle)), "Cannot close synthetic fixture file lock")


def make_junction(path: Path, target: Path, environment: dict, log) -> None:
    native.require(not path.exists() and not path.is_symlink(), "Junction destination must be new")
    # Both operands are fixed child paths generated by this program. No shell
    # command comes from external/user content; no privilege or policy change.
    command = [str(Path(os.environ["SystemRoot"]) / "System32/cmd.exe"),
               "/d", "/c", "mklink", "/J", str(path), str(target)]
    result = subprocess.run(command, env=environment, stdout=log, stderr=subprocess.STDOUT,
                            timeout=20, check=False)
    native.require(result.returncode == 0 and native.is_link_or_reparse(path), "Cannot create static synthetic junction")
    info = path.lstat()
    native.require(getattr(info, "st_reparse_tag", None) == 0xA0000003,
                   "Synthetic reparse point is not the expected directory junction")


def remove_junction(path: Path) -> None:
    """Remove only the just-created junction object, never its target tree."""
    native.require(native.is_link_or_reparse(path)
                   and getattr(path.lstat(), "st_reparse_tag", None) == 0xA0000003,
                   "Synthetic junction identity changed")
    os.rmdir(path)


def run_fixture(executable: Path, arguments: list[str], root: Path, environment: dict,
                log, commands: list[dict]) -> int:
    native.require(executable in (root / FIXTURE_EXE, root / "app/uninstall.exe"),
                   "Only the two explicitly generated synthetic executables may run")
    relative = executable.relative_to(root).as_posix()
    native.regular_file(root, relative)
    command = [str(executable), *arguments]
    record = {"argv": command, "sha256": native.digest(executable), "exit_code": None}
    commands.append(record)
    log.write((json.dumps({"argv": command}, ensure_ascii=True) + "\n").encode())
    log.flush()
    process = subprocess.Popen(command, cwd=root, env=environment,
                               stdout=log, stderr=subprocess.STDOUT)
    record["started"] = True
    try:
        record["exit_code"] = process.wait(timeout=90)
    except subprocess.TimeoutExpired:
        record["timed_out"] = True
        # Terminate only the process tree just created by this test.
        killer = str(Path(os.environ["SystemRoot"]) / "System32/taskkill.exe")
        subprocess.run([killer, "/PID", str(process.pid), "/T", "/F"],
                       stdout=log, stderr=subprocess.STDOUT, timeout=20, check=False)
        raise ValueError("Synthetic safety process timed out")
    return record["exit_code"]



def validate_shortcut_readback(report: dict) -> None:
    """Independently enforce the bounded fixed reader contract, never a fallback.

    This validates retained observations; it does not emulate Windows COM or
    count portable/model tests as actual Windows shortcut readback.
    """
    native.require(report.get("schema_version") == 1 and report.get("passed") is True
                   and report.get("fixture_root") == SHORTCUT_ROOT and report.get("case_count") == 3,
                   "Synthetic shortcut readback did not pass")
    for name in ("browser_executed", "shortcut_executed", "resolve_called", "save_called",
                 "production_installer_tested", "release_eligible"):
        native.require(report.get(name) is False, "Unexpected synthetic shortcut execution/persistence claim")
    native.require(report.get("get_path_flags") == 0 and report.get("persist_load_mode") == 0
                   and report.get("error_type") is None and report.get("error_hresult") is None,
                   "Unexpected synthetic shortcut reader mode/error")
    cases = report.get("cases")
    native.require(isinstance(cases, list) and len(cases) == len(SHORTCUT_CASES), "Missing shortcut cases")
    for case, (case_id, folder, profile) in zip(cases, SHORTCUT_CASES):
        native.require(isinstance(case, dict), "Invalid shortcut case")
        directory = ntpath.join(SHORTCUT_ROOT, folder)
        ascii_directory = ntpath.join(SHORTCUT_ROOT, "ascii-link-copies-" + case_id)
        expected = {"target": ntpath.join(directory, "privacybrowser.exe"),
                    "arguments": '-no-remote -profile "' + ntpath.join(SHORTCUT_ROOT, "profiles", profile) + '"',
                    "icon": ntpath.join(directory, "reference.ico"), "icon_index": 0,
                    "working_directory": directory}
        native.require(case.get("id") == case_id and case.get("expected") == expected
                       and case.get("passed") is True and case.get("copies_identical") is True
                       and case.get("files_unchanged") is True and case.get("error_type") is None
                       and case.get("error_hresult") is None, "Synthetic shortcut case failed")
        native.require(ascii_directory.isascii() and case.get("ascii_copy_directory") == ascii_directory
                       and case.get("ascii_copies_identical") is True, "Invalid ASCII shortcut copy control")
        links = case.get("links")
        fixed_links = [(kind, ntpath.join(directory, relative), wsh) for kind, relative, wsh in SHORTCUT_LINKS]
        fixed_links += [(kind, ntpath.join(ascii_directory, relative), wsh)
                        for kind, relative, wsh in SHORTCUT_ASCII_LINKS]
        native.require(isinstance(links, list) and len(links) == len(fixed_links), "Missing shortcut observations")
        for link, (kind, path, wsh_required) in zip(links, fixed_links):
            native.require(isinstance(link, dict), "Invalid shortcut observation")
            before = link.get("sha256_before")
            identity = link.get("identity_before")
            native.require(link.get("kind") == kind and link.get("path") == path
                           and link.get("passed") is True and link.get("wsh_required") is wsh_required
                           and isinstance(link.get("bytes"), int) and 0 < link["bytes"] <= 65536
                           and isinstance(before, str) and len(before) == 64
                           and all(value in "0123456789abcdef" for value in before)
                           and before == link.get("sha256_after")
                           and isinstance(identity, str) and len(identity) == 26
                           and identity == link.get("identity_after"), "Shortcut bytes or fixed identity changed")
            wide = link.get("wide")
            native.require(isinstance(wide, dict) and wide.get("load_mode") == 0 and wide.get("path_flags") == 0,
                           "Missing explicit wide shortcut reader")
            for name in ("load_hresult", "target_hresult", "arguments_hresult", "icon_hresult", "working_directory_hresult"):
                native.require(type(wide.get(name)) is int and wide[name] == 0, "Wide shortcut HRESULT failed")
            readers = [wide]
            if wsh_required:
                wsh = link.get("wsh")
                native.require(isinstance(wsh, dict) and wsh.get("read_succeeded") is True,
                               "WSH shortcut reader failed")
                readers.append(wsh)
            else:
                native.require(link.get("wsh") is None, "WSH must not open custom-extension snapshots")
            for actual in readers:
                native.require(actual.get("strings_within_bound") is True and actual.get("error_type") is None
                               and actual.get("error_hresult") is None, "Shortcut reader returned an error")
                for name, value in expected.items():
                    observed = actual.get(name)
                    if name == "target":
                        native.require(isinstance(observed, str) and observed.lower() == value.lower(),
                                       "Shortcut target mismatch")
                    else:
                        native.require(type(observed) is type(value) and observed == value,
                                       "Shortcut " + name + " mismatch")
        for source, copied in ((1, 3), (2, 4), (1, 5), (2, 6)):
            native.require(links[source]["sha256_before"] == links[copied]["sha256_before"]
                           and links[source]["bytes"] == links[copied]["bytes"], "Shortcut copy mismatch")


def run_shortcut_readback(work: Path, root: Path, environment: dict, log, commands: list[dict]) -> dict:
    """Invoke only our fixed installed PowerShell reader, before destructive tests."""
    require_host(work)
    native.require(root == work / EXECUTION_RELATIVE, "Unexpected shortcut fixture root")
    evidence = work / "evidence"
    native.require(evidence.is_dir() and not native.is_link_or_reparse(evidence), "Unsafe shortcut evidence directory")
    output = evidence / SHORTCUT_OUTPUT
    native.require(not output.exists() and not output.is_symlink(), "Shortcut evidence must be new")
    script = native.regular_file(Path(__file__).resolve().parent, "test_windows_shortcut_readback.ps1")
    # The hosted Windows image supplies this engine; never download an engine,
    # take a caller-supplied command, or change execution policy/profile settings.
    engine = native.regular_file(Path(r"C:\Program Files\PowerShell\7"), "pwsh.exe")
    command = [str(engine), "-NoLogo", "-NoProfile", "-NonInteractive", "-File", str(script)]
    record = {"kind": "synthetic-shortcut-readback", "argv": command,
              "script_sha256": native.digest(script), "exit_code": None, "evidence": None}
    commands.append(record)
    try:
        result = subprocess.run(command, cwd=root, env=environment, stdout=log,
                                stderr=subprocess.STDOUT, timeout=60, check=False)
        record["exit_code"] = result.returncode
        native.require(result.returncode == 0, "Synthetic shortcut readback failed; retain shortcut diagnostics")
        native.require(output.is_file(), "Missing shortcut report")
        path = native.regular_file(evidence, SHORTCUT_OUTPUT)
        native.require(0 < path.stat().st_size <= SHORTCUT_MAX_BYTES, "Invalid shortcut report size")
        report = json.loads(path.read_text(encoding="utf-8"))
        native.require(isinstance(report, dict), "Invalid shortcut report")
        validate_shortcut_readback(report)
    except subprocess.TimeoutExpired:
        record["timed_out"] = True
        raise
    finally:
        # Failure output is evidence too. Do not discard or rewrite the report,
        # or let an unsuccessful reader become a successful synthetic check.
        if output.exists() and not native.is_link_or_reparse(output) and output.is_file():
            size = output.stat().st_size
            record["evidence"] = {"path": output.name, "bytes": size,
                                  "sha256": native.digest(output) if size <= SHORTCUT_MAX_BYTES else None}
            if size > SHORTCUT_MAX_BYTES:
                record["evidence"]["oversized"] = True
    return record["evidence"]


def execute_synthetic(work: Path, compilation: dict) -> dict:
    require_host(work)
    root = work / EXECUTION_RELATIVE
    executable = native.regular_file(root, FIXTURE_EXE)
    native.require(compilation.get("synthetic_fixture_compiled") is True
                   and compilation.get("fixture_root") == EXECUTION_WINDOWS
                   and compilation.get("generated_installer_sha256") == native.digest(executable)
                   and compilation.get("release_eligible") is False,
                   "Matching synthetic compilation evidence is required")
    evidence = work / "evidence"
    output, logfile = evidence / "installer-synthetic-execution.json", evidence / "installer-synthetic-execution.log"
    native.require(not output.exists() and not logfile.exists(), "Synthetic execution evidence must be new")
    # The second compiler creates exactly its output here. Refuse reuse before
    # creating any runtime fixtures or launching any generated code.
    native.require(list(root.iterdir()) == [executable], "Synthetic execution root is not fresh")
    checks, commands = {}, []
    report = {"schema_version": 1, "purpose": "isolated synthetic NSIS safety-function execution",
              "fixture_root": EXECUTION_WINDOWS, "synthetic_fixture_sha256": native.digest(executable),
              "synthetic_fixture_executed": False, "passed": False, "checks": checks, "commands": commands,
              "production_syntax_installer_executed": False, "browser_executed": False,
              "system_settings_changed": False, "generated_executables_uploaded": False,
              "official_release": False, "release_eligible": False,
              "limitations": "Synthetic files only; later genuine browser and installer gates remain mandatory."}
    environment = fixture_environment(root)
    with logfile.open("xb") as log:
        try:
            for name in ("tmp", "local", "roaming", "foreign"):
                (root / name).mkdir()
            ordinary = root / "ordinary-日本語.txt"
            ordinary.write_bytes(b"ordinary Unicode native-open fixture; retain")
            foreign = root / "foreign/retain.txt"
            foreign.write_bytes(b"foreign synthetic sibling; must never be removed")
            retained = {ordinary: native.digest(ordinary), foreign: native.digest(foreign)}
            app = root / "app"
            protected = [root / name for name in ("local", "roaming", "foreign")]
            protected_baseline = snapshot(protected)

            def refuse_creation(case: str) -> None:
                log.write((json.dumps({"creation_collision": case}) + "\n").encode())
                native.require(run_fixture(executable, ["/S"], root, environment, log, commands) != 0,
                               f"Synthetic existing {case} application path was not refused")
                native.require(snapshot(protected) == protected_baseline,
                               f"Synthetic {case} refusal changed data outside the application path")
                for path, expected in retained.items():
                    native.require(path.is_file() and native.digest(path) == expected,
                                   f"Synthetic {case} refusal changed a retained fixture")

            def application_identity() -> tuple[int, int, int]:
                info = app.lstat()
                return info.st_dev, info.st_ino, info.st_mode

            # Authored collisions are removed only after proving that the
            # installer refused them untouched. No existing object is adopted.
            app.mkdir()
            empty_identity = application_identity()
            refuse_creation("empty directory")
            native.require(application_identity() == empty_identity and snapshot([app]) == {},
                           "Synthetic empty application directory was changed")
            app.rmdir()
            checks["existing_empty_application_directory_refused_untouched"] = True

            app.mkdir()
            (app / "nested").mkdir()
            collision = app / "nested/retain-日本語.txt"
            collision.write_bytes(b"existing synthetic application data; retain exactly")
            nonempty_identity, nonempty_baseline = application_identity(), snapshot([app])
            refuse_creation("nonempty directory")
            native.require(application_identity() == nonempty_identity and snapshot([app]) == nonempty_baseline,
                           "Synthetic nonempty application directory was changed")
            collision.unlink()
            (app / "nested").rmdir()
            app.rmdir()
            checks["existing_nonempty_application_directory_refused_untouched"] = True

            app.write_bytes(b"existing synthetic file at application path; retain exactly")
            file_identity, file_hash = application_identity(), native.digest(app)
            refuse_creation("file")
            native.require(application_identity() == file_identity and native.digest(app) == file_hash,
                           "Synthetic application file collision was changed")
            app.unlink()
            checks["existing_application_file_refused_untouched"] = True

            make_junction(app, foreign.parent, environment, log)
            junction_identity, junction_target = application_identity(), os.readlink(app)
            try:
                refuse_creation("junction")
                native.require(application_identity() == junction_identity
                               and native.is_link_or_reparse(app) and os.readlink(app) == junction_target,
                               "Synthetic application junction was changed")
            finally:
                remove_junction(app)
            checks["existing_application_junction_refused_untouched"] = True

            native.require(not app.exists() and not app.is_symlink(), "Synthetic application path must be fresh")
            result = run_fixture(executable, ["/S"], root, environment, log, commands)
            native.require(result == 0, "Synthetic initialization/ordinary Unicode NT open failed")
            native.require(app.is_dir() and not native.is_link_or_reparse(app),
                           "Fresh synthetic application directory was not created safely")
            uninstaller = native.regular_file(root, "app/uninstall.exe")
            uninstaller_hash = native.digest(uninstaller)
            checks["fresh_application_directory_created"] = True
            owned = [root / "local/PrivacyBrowser", root / "roaming/PrivacyBrowser"]
            for path in owned:
                expected = ("PrivacyBrowser-UserData-v1\r\n" + str(app) + "\r\n" + str(path) + "\r\n").encode("utf-16-le")
                native.require((path / MARKER).read_bytes() == expected, "Synthetic Unicode owner marker mismatch")
            checks["ordinary_unicode_nt_open_and_owned_markers"] = True
            report["shortcut_readback"] = run_shortcut_readback(work, root, environment, log, commands)
            checks["synthetic_shortcut_roundtrip_readback"] = True
            nested = owned[0] / "Profile-日本語/nested"
            nested.mkdir(parents=True)
            for index in range(FILE_COUNT):
                (nested / f"entry-{index:04d}-日本語-long-enumeration-name.txt").write_bytes(f"synthetic value {index}\n".encode())
            (nested / "supplementary-\U0001f642.txt").write_bytes(b"supplementary Unicode filename fixture")
            (owned[0] / "Profile-日本語/parent.lock").write_bytes(b"")
            locked = owned[1] / "locked-fixture.txt"
            locked.write_bytes(b"locked fixture; must survive refused purge")
            baseline = snapshot(owned)

            def uninstall() -> int:
                native.require(native.digest(uninstaller) == uninstaller_hash, "Synthetic uninstaller changed")
                return run_fixture(uninstaller, ["/S", "_?=" + str(app)], root, environment, log, commands)

            marker = owned[0] / MARKER
            good = marker.read_bytes()
            marker.write_bytes(b"invalid synthetic ownership marker")
            corrupted = snapshot(owned)
            native.require(uninstall() != 0, "Synthetic invalid owner marker was not refused")
            native.require(snapshot(owned) == corrupted, "Marker refusal changed synthetic data")
            marker.write_bytes(good)
            checks["invalid_marker_refused_without_deletion"] = True

            with locked_file(locked):
                native.require(uninstall() != 0, "Synthetic locked file was not refused")
            native.require(snapshot(owned) == baseline, "Locked-file refusal changed synthetic data")
            checks["locked_file_refused_before_any_deletion"] = True

            junction = owned[0] / "junction-fixture"
            make_junction(junction, foreign.parent, environment, log)
            try:
                native.require(uninstall() != 0, "Synthetic static junction was not refused")
                native.require(native.digest(foreign) == retained[foreign], "Junction target was changed")
            finally:
                remove_junction(junction)
            native.require(snapshot(owned) == baseline, "Junction refusal changed synthetic data")
            checks["static_junction_refused_without_target_deletion"] = True

            native.require(uninstall() == 0, "Synthetic owned-tree cleanup failed")
            native.require(all(not path.exists() for path in owned), "Synthetic owned roots were not completely removed")
            checks["native_handle_enumeration_and_marker_last_deletion"] = True
            checks["multi_buffer_unicode_tree_removed"] = True
            native.require(uninstall() == 0, "Synthetic cleanup retry after removed roots failed")
            checks["missing_owned_roots_retry_safe"] = True
            for path, expected in retained.items():
                native.require(path.is_file() and native.digest(path) == expected, "Synthetic sibling file was changed")
            native.require(native.digest(uninstaller) == uninstaller_hash, "Synthetic harness uninstaller was changed")
            checks["foreign_siblings_and_harness_retained"] = True
            report["fixture_data_files"] = FILE_COUNT + 3
            report["passed"] = True
        except (OSError, ValueError, subprocess.SubprocessError) as error:
            report["error"] = str(error)
            raise
        finally:
            report["synthetic_fixture_executed"] = any(item.get("started") is True for item in commands)
            log.flush()
            report["log"] = {"path": logfile.name, "sha256": native.digest(logfile)}
            write_json(output, report)
    return report
