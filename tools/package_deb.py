#!/usr/bin/env python3
"""Package a complete locally tested developer runtime; never claim a source build."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def package(runtime: Path, output: Path) -> Path:
    runtime = runtime.resolve()
    evidence_file = runtime / "PRIVACY_BROWSER_BUILD.json"
    if not evidence_file.is_file() or not (runtime / "privacy-browser-dev").is_file():
        raise ValueError("Pass a complete developer runtime generated by tools/build_dev.py")
    evidence = json.loads(evidence_file.read_text())
    if evidence.get("build_kind") != "developer-runtime-overlay" or evidence.get("official_release") is not False:
        raise ValueError("This packager accepts explicitly unofficial developer builds only")
    output = output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="privacybrowser-deb-") as temporary:
        stage = Path(temporary)
        app = stage / "opt" / "privacy-browser-dev"
        app.parent.mkdir(parents=True)
        shutil.copytree(runtime, app, symlinks=True)
        binary = stage / "usr" / "bin"
        binary.mkdir(parents=True)
        binary_launcher = binary / "privacy-browser-dev"
        binary_launcher.write_text('#!/bin/sh\nexec /opt/privacy-browser-dev/privacy-browser-dev "$@"\n')
        binary_launcher.chmod(0o755)
        desktop = stage / "usr" / "share" / "applications"
        desktop.mkdir(parents=True)
        shutil.copyfile(ROOT / "packaging/linux/privacy-browser-dev.desktop", desktop / "privacy-browser-dev.desktop")
        icon = runtime / "distribution/privacybrowser/assets/privacybrowser.svg"
        if not icon.exists():
            icon = runtime / "distribution/privacybrowser/assets/logo.svg"
        if icon.exists():
            icons = stage / "usr/share/icons/hicolor/scalable/apps"
            icons.mkdir(parents=True)
            shutil.copyfile(icon, icons / "privacy-browser-dev.svg")
        control = stage / "DEBIAN"
        control.mkdir()
        size = sum(path.stat().st_size for path in app.rglob("*") if path.is_file()) // 1024
        (control / "control").write_text(f'''Package: privacy-browser-dev
Version: 0.1.0~dev1
Section: web
Priority: optional
Architecture: amd64
Maintainer: Privacy Browser contributors <noreply@example.invalid>
Depends: libc6 (>= 2.35), libstdc++6, libgtk-3-0, libdbus-glib-1-2, libasound2 | libasound2t64, libx11-xcb1, libxt6, libxcomposite1, libxdamage1, libxfixes3, libxrandr2
Installed-Size: {size}
Description: Privacy Browser developer runtime overlay (unofficial)
 Complete upstream ESR runtime with experimental Privacy Browser chrome.
 Local development build, not an independently compiled branded release.
 Automatic updates are disabled pending a signed project update service.
''')
        subprocess.run(["dpkg-deb", "--root-owner-group", "--build", str(stage), str(output)], check=True)
    return output


def package_bootstrap(output: Path) -> Path:
    """Create an adapter package with project code only; no Firefox binary."""
    output = output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="privacybrowser-bootstrap-deb-") as temporary:
        stage = Path(temporary)
        project = stage / "usr/share/privacy-browser-dev"
        project.mkdir(parents=True)
        shutil.copytree(ROOT / "browser/privacy", project / "browser/privacy")
        shutil.copytree(ROOT / "config", project / "config")
        (project / "tools").mkdir()
        for name in ("build_dev.py", "dev_launcher.py"):
            shutil.copyfile(ROOT / "tools" / name, project / "tools" / name)
        launcher = stage / "usr/bin/privacy-browser-dev"
        launcher.parent.mkdir(parents=True)
        launcher.write_text('#!/bin/sh\nexec python3 -B /usr/share/privacy-browser-dev/tools/dev_launcher.py --project /usr/share/privacy-browser-dev "$@"\n')
        launcher.chmod(0o755)
        desktop = stage / "usr/share/applications"
        desktop.mkdir(parents=True)
        shutil.copyfile(ROOT / "packaging/linux/privacy-browser-dev.desktop", desktop / "privacy-browser-dev.desktop")
        icons = stage / "usr/share/icons/hicolor/scalable/apps"
        icons.mkdir(parents=True)
        shutil.copyfile(ROOT / "browser/privacy/assets/privacybrowser.svg", icons / "privacy-browser-dev.svg")
        documentation = stage / "usr/share/doc/privacy-browser-dev-bootstrap"
        documentation.mkdir(parents=True)
        for name in ("LICENSE", "LICENSE.md", "NOTICE", "NOTICE.md", "README.md"):
            source = ROOT / name
            if source.is_file():
                shutil.copyfile(source, documentation / name)
        if (ROOT / "docs").is_dir():
            shutil.copytree(ROOT / "docs", documentation / "docs")
        shutil.copyfile(ROOT / "packaging/README.md", documentation / "PACKAGING.md")
        metadata = stage / "DEBIAN"
        metadata.mkdir()
        (metadata / "control").write_text('''Package: privacy-browser-dev-bootstrap
Version: 0.1.0~dev1
Section: web
Priority: optional
Architecture: all
Maintainer: Privacy Browser contributors <noreply@example.invalid>
Depends: python3 (>= 3.11)
Recommends: firefox-esr
Description: Privacy Browser experimental chrome adapter (external ESR required)
 This package contains project chrome, launcher and developer tools only.
 It does NOT contain an independently compiled browser or a Gecko binary.
 A separately obtained matching Firefox ESR runtime is required. The launcher
 copies it into a private cache and never modifies the system installation.
 Browser profiles are separate; automatic updates are disabled in the copy.
''')
        subprocess.run(["dpkg-deb", "--root-owner-group", "--build", str(stage), str(output)], check=True)
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runtime", type=Path)
    parser.add_argument("--bootstrap-only", action="store_true", help="Package project code only; external ESR runtime required")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.bootstrap_only:
        print(package_bootstrap(args.output))
    elif args.runtime:
        print(package(args.runtime, args.output))
    else:
        parser.error("Pass --bootstrap-only or --runtime DIRECTORY")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        raise SystemExit(f"DEB packaging failed: {error}")
